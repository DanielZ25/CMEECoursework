# ============================================================
# Ordering Experiment (V6, 6 fields) — exhaustive 720 permutations
# Goal: search for the input field ORDER that maximises cluster
#       discernibility (Samraat's "optimal sequence"), and separately
#       test whether order matters at all (ARI vs original).
# ============================================================
# Field set is FIXED at the 6 V6 fields. We permute their ORDER only:
#   name, def, unit, order, family, stage   -> 6! = 720 orderings
#
# Scoring per ordering:
#   - silhouette (non-noise points only)  = PRIMARY ranking metric
#   - n_clusters, noise_rate, avg_cluster_size, max_cluster_share = descriptive
#   - max_cluster_share                    = degeneracy guardrail
#   - ARI vs original                      = "does order even matter?"
#
# Baseline = the ORIGINAL order (name>def>unit>order>family>stage),
# read directly from embeddings_v6.npy (no API call), because that npy
# was generated from exactly this ordering.
#
# Prereqs in the R session (run analysis.R / analysis_more_inputs.R first):
#   - rows           : read_csv("Data/VecTraits.csv")
#   - get_embeddings : OpenAI text-embedding-3-large wrapper
#   - hdbscan_pkg    : import("hdbscan")
#   - OPENAI_API_KEY set
#   - pymc-env must also have scikit-learn installed (for silhouette)
# ------------------------------------------------------------

library(tidyverse)
library(reticulate)
library(mclust)     # adjustedRandIndex
library(digest)     # text hashing for dedup cache

setwd("/Users/danielzhu/Documents/Master Project")
dir.create("Results/ordering_cache", showWarnings = FALSE)  # new subdir for embedding cache


# ── 1. Rebuild V6 rows EXACTLY as analysis_more_inputs.R (=> 467 rows) ──
v6_base <- rows %>%
  mutate(across(c(OriginalTraitName, OriginalTraitDef, OriginalTraitUnit,
                  Interactor1Order, Interactor1Family, Interactor1Stage),
                str_trim)) %>%
  distinct(OriginalTraitName, OriginalTraitDef, .keep_all = TRUE) %>%
  select(OriginalTraitName, OriginalTraitDef, OriginalTraitUnit,
         Interactor1Order, Interactor1Family, Interactor1Stage)

cat("V6 reconstructed rows:", nrow(v6_base), "\n")
# NOTE: baseline (original order) is re-embedded from v6_base itself, NOT read
# from embeddings_v6.npy. That npy was generated by a different dedup (467 rows)
# and would be row-misaligned with this 461-row reconstruction. Re-embedding the
# baseline guarantees all 720 orderings share identical rows / row order.
N_ROWS <- nrow(v6_base)

# ── 2. Six field blocks (same templates/labels as the V6 pipeline) ──
blocks <- list(
  name   = function(d) paste0("Trait: ", d$OriginalTraitName),
  def    = function(d) paste0("Definition: ", d$OriginalTraitDef),
  unit   = function(d) paste0("Unit: ", d$OriginalTraitUnit),
  order  = function(d) paste0("Organism order: ", d$Interactor1Order),
  family = function(d) paste0("Organism family: ", d$Interactor1Family),
  stage  = function(d) paste0("Life stage: ",
                              ifelse(is.na(d$Interactor1Stage) | d$Interactor1Stage == "",
                                     "not specified", d$Interactor1Stage))
)
block_names <- names(blocks)                       # canonical/original order
block_strings <- lapply(blocks, function(f) f(v6_base))

assemble_text <- function(order_vec) {
  parts <- block_strings[order_vec]
  body  <- do.call(paste, c(parts, sep = ". "))
  paste0(body, ".")
}

# ── 3. Enumerate ALL 720 permutations + label named anchors ─────
library(gtools)  # permutations(); install.packages("gtools") if missing
all_perms <- permutations(n = 6, r = 6, v = block_names)   # 720 x 6 matrix
cat("Total permutations:", nrow(all_perms), "\n")

named_anchor <- function(vec) {
  s <- paste(vec, collapse = ">")
  dplyr::case_when(
    s == "name>def>unit>order>family>stage" ~ "original",
    s == "stage>family>order>unit>def>name" ~ "reversed",
    s == "def>name>unit>order>family>stage" ~ "def_first",
    s == "order>family>stage>name>def>unit" ~ "taxonomy_first",
    s == "unit>name>def>order>family>stage" ~ "unit_first",
    TRUE ~ NA_character_
  )
}

# ── 4. HDBSCAN + silhouette helpers ─────────────────────────────
sklearn <- import("sklearn.metrics")

run_hdbscan <- function(emb) {
  clusterer <- hdbscan_pkg$HDBSCAN(
    min_cluster_size = 5L, min_samples = 3L, metric = "euclidean"
  )
  as.vector(clusterer$fit_predict(emb))
}

# silhouette on NON-noise points only; needs >=2 clusters among them
silhouette_nonnoise <- function(emb, labels) {
  keep <- labels != -1
  lab  <- labels[keep]
  if (length(unique(lab)) < 2) return(NA_real_)
  sub  <- emb[keep, , drop = FALSE]
  tryCatch(
    sklearn$silhouette_score(sub, as.integer(lab), metric = "euclidean"),
    error = function(e) NA_real_
  )
}

cluster_stats <- function(labels) {
  non_noise <- labels[labels != -1]
  n_clusters <- length(unique(non_noise))
  n_noise    <- sum(labels == -1)
  tab        <- as.data.frame(table(non_noise))   # avoids 'list' dplyr bug
  sizes      <- if (nrow(tab) > 0) tab$Freq else 0
  list(
    n_clusters       = n_clusters,
    n_noise          = n_noise,
    noise_rate       = round(n_noise / length(labels), 4),
    avg_cluster_size = if (n_clusters > 0) round(mean(sizes), 2) else 0,
    max_cluster_share= if (length(non_noise) > 0)
      round(max(sizes) / length(labels), 4) else 0
  )
}

# ── 5. Dedup-cached embedding: cache by md5 of the full text vector ──
# Many orderings could in principle collide; we cache on the exact text
# vector so nothing is ever embedded twice (also survives restarts).
embed_cached <- function(texts) {
  key        <- digest(texts, algo = "md5")
  cache_file <- sprintf("Results/ordering_cache/%s.rds", key)
  if (file.exists(cache_file)) return(readRDS(cache_file))
  batch_size <- 100
  acc <- list()
  for (i in seq(1, length(texts), by = batch_size)) {
    batch <- texts[i:min(i + batch_size - 1, length(texts))]
    acc[[length(acc) + 1]] <- get_embeddings(batch)
  }
  emb <- do.call(rbind, acc)
  saveRDS(emb, cache_file)
  emb
}

# ── 6. Baseline = ORIGINAL order, re-embedded from v6_base ──────
# (NOT from embeddings_v6.npy — see note in section 1 about row mismatch.)
# This call is cached too, so it only hits the API once across reruns.
emb_original    <- embed_cached(assemble_text(block_names))
stopifnot(nrow(emb_original) == N_ROWS)
labels_original <- run_hdbscan(emb_original)

cat("Example original text:\n  ", assemble_text(block_names)[1], "\n\n")

# ── 7. Main loop over all 720 permutations ──────────────────────
n_perm <- nrow(all_perms)
results <- vector("list", n_perm)
pb_every <- 25

t0 <- Sys.time()
for (k in seq_len(n_perm)) {
  ord_vec <- as.character(all_perms[k, ])
  ord_str <- paste(ord_vec, collapse = ">")
  anchor  <- named_anchor(ord_vec)
  is_orig <- identical(ord_vec, block_names)
  
  if (is_orig) {
    labels <- labels_original           # baseline (already embedded above)
  } else {
    texts  <- assemble_text(ord_vec)
    emb    <- embed_cached(texts)
    labels <- run_hdbscan(emb)
  }
  
  st  <- cluster_stats(labels)
  sil <- if (is_orig) silhouette_nonnoise(emb_original, labels)
  else          silhouette_nonnoise(emb, labels)
  ari <- adjustedRandIndex(labels_original, labels)
  
  results[[k]] <- data.frame(
    perm_id          = k,
    order_string     = ord_str,
    anchor           = ifelse(is.na(anchor), "", anchor),
    silhouette       = round(sil, 4),
    n_clusters       = st$n_clusters,
    noise_rate       = st$noise_rate,
    avg_cluster_size = st$avg_cluster_size,
    max_cluster_share= st$max_cluster_share,
    ARI_vs_original  = round(ari, 4),
    stringsAsFactors = FALSE
  )
  
  if (k %% pb_every == 0 || k == n_perm) {
    el <- round(as.numeric(difftime(Sys.time(), t0, units = "mins")), 1)
    cat(sprintf("  %d/%d done (%.1f min elapsed)\n", k, n_perm, el))
  }
}

ordering_results <- bind_rows(results)

# ── 8. Degeneracy flag + ranking ────────────────────────────────
# Guardrail: a high silhouette is NOT trustworthy if one giant cluster
# swallowed most points (the BioTraits 2-cluster / GMM garbage-bin mode).
DEGEN_THRESHOLD <- 0.5   # flag if largest cluster holds >50% of all points
ordering_results <- ordering_results %>%
  mutate(degenerate = max_cluster_share > DEGEN_THRESHOLD)

ranked <- ordering_results %>%
  arrange(desc(!degenerate), desc(silhouette))   # valid first, then by silhouette

cat("\n=== TOP 10 ORDERINGS (degenerate excluded first) ===\n")
print(head(ranked %>%
             select(anchor, order_string, silhouette, n_clusters,
                    noise_rate, max_cluster_share, ARI_vs_original, degenerate), 10))

cat("\n=== NAMED ANCHORS ===\n")
print(ordering_results %>% filter(anchor != "") %>%
        select(anchor, silhouette, n_clusters, noise_rate,
               max_cluster_share, ARI_vs_original, degenerate))

# ── 9. "Does order matter?" summary (ARI distribution) ──────────
cat("\n=== ARI vs original — distribution across all 720 orderings ===\n")
print(summary(ordering_results$ARI_vs_original))
cat(sprintf("Orderings with ARI == 1.000 (identical to original): %d / %d\n",
            sum(ordering_results$ARI_vs_original >= 0.9999), n_perm))
cat(sprintf("Silhouette range: %.4f to %.4f\n",
            min(ordering_results$silhouette, na.rm = TRUE),
            max(ordering_results$silhouette, na.rm = TRUE)))

# ── 10. Save ────────────────────────────────────────────────────
write_csv(ordering_results, "Results/ordering_720_full.csv")
write_csv(ranked,           "Results/ordering_720_ranked.csv")
cat("\nSaved: Results/ordering_720_full.csv\n")
cat("Saved: Results/ordering_720_ranked.csv\n")
cat(sprintf("\nTotal runtime: %.1f min\n",
            as.numeric(difftime(Sys.time(), t0, units = "mins"))))
cat("Done.\n")
